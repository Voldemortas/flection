/**
 * normalises letters~diacritics from various Latin scripts into Lithuanian letters
 * @param text - the text full of diacritics
 */
export function normaliseAccents(text: string): string {
  return text
    .replaceAll(/(i)\u0307/gi, `$1`)
    .replaceAll(/á/g, `a\u0301`)
    .replaceAll(/á\u0328/g, `ą\u0301`)
    .replaceAll(/é/g, `e\u0301`)
    .replaceAll(/é\u0328/g, `ę\u0301`)
    .replaceAll(/ó/g, `o\u0301`)
    .replaceAll(/í/g, `i\u0301`)
    .replaceAll(/í\u0328/g, `į\u0301`)
    .replaceAll(/ú/g, `u\u0301`)
    .replaceAll(/ú\u0328/g, `ų\u0301`)
    .replaceAll(/ý/g, `y\u0301`)
    .replaceAll(/Á/g, `A\u0301`)
    .replaceAll(/Á\u0328/g, `Ą\u0301`)
    .replaceAll(/É/g, `E\u0301`)
    .replaceAll(/É\u0328/g, `Ę\u0301`)
    .replaceAll(/Ó/g, `O\u0301`)
    .replaceAll(/Í/g, `I\u0301`)
    .replaceAll(/Í\u0328/g, `Į\u0301`)
    .replaceAll(/Ú/g, `U\u0301`)
    .replaceAll(/Ú\u0328/g, `Ų\u0301`)
    .replaceAll(/Ý/g, `Y\u0301`)
    .replaceAll(/à/g, `a\u0300`)
    .replaceAll(/è/g, `e\u0300`)
    .replaceAll(/ò/g, `o\u0300`)
    .replaceAll(/ì/g, `i\u0300`)
    .replaceAll(/ù/g, `u\u0300`)
    .replaceAll(/À/g, `A\u0300`)
    .replaceAll(/È/g, `E\u0300`)
    .replaceAll(/Ò/g, `O\u0300`)
    .replaceAll(/Ì/g, `I\u0300`)
    .replaceAll(/Ù/g, `U\u0300`)
    .replaceAll(/ã/g, `a\u0303`)
    .replaceAll(/ã\u0328/g, `ą\u0303`)
    .replaceAll(/ẽ/g, `e\u0303`)
    .replaceAll(/ẽ\u0328/g, `ę\u0303`)
    .replaceAll(/õ/g, `o\u0303`)
    .replaceAll(/ĩ/g, `i\u0303`)
    .replaceAll(/ĩ\u0328/g, `į\u0303`)
    .replaceAll(/ũ/g, `u\u0303`)
    .replaceAll(/ũ\u0328/g, `ų\u0303`)
    .replaceAll(/ỹ/g, `y\u0303`)
    .replaceAll(/Ã/g, `A\u0303`)
    .replaceAll(/Ã\u0328/g, `Ą\u0303`)
    .replaceAll(/Ẽ/g, `E\u0303`)
    .replaceAll(/Ẽ\u0328/g, `Ę\u0303`)
    .replaceAll(/Õ/g, `O\u0303`)
    .replaceAll(/Ĩ/g, `I\u0303`)
    .replaceAll(/Ĩ\u0328/g, `Į\u0303`)
    .replaceAll(/Ũ/g, `U\u0303`)
    .replaceAll(/Ũ\u0328/g, `Ų\u0303`)
    .replaceAll(/Ỹ/g, `Y\u0303`)
    .replaceAll(/ñ/g, `n\u0303`)
    .replaceAll(/Ñ/g, `N\u0303`)
    .replaceAll(/a([\u0301\u0303])?\u0328/g, `ą$1`)
    .replaceAll(/A([\u0301\u0303])?\u0328/g, `Ą$1`)
    .replaceAll(/e([\u0301\u0303])?\u0328/g, `ę$1`)
    .replaceAll(/E([\u0301\u0303])?\u0328/g, `Ę$1`)
    .replaceAll(/u([\u0301\u0303])?\u0328/g, `ų$1`)
    .replaceAll(/U([\u0301\u0303])?\u0328/g, `Ų$1`)
    .replaceAll(/i([\u0301\u0303])?\u0328/g, `į$1`)
    .replaceAll(/I([\u0301\u0303])?\u0328/g, `Į$1`)
    .replaceAll(/e([\u0301\u0303])?\u0307/g, `ė$1`)
    .replaceAll(/E([\u0301\u0303])?\u0307/g, `Ė$1`)
    .replaceAll(/c\u030C/g, `č`)
    .replaceAll(/C\u030C/g, `Č`)
    .replaceAll(/s\u030C/g, `š`)
    .replaceAll(/S\u030C/g, `Š`)
    .replaceAll(/z\u030C/g, `ž`)
    .replaceAll(/Z\u030C/g, `Ž`)
    .replaceAll(/u([\u0301\u0303])?\u0304/g, `ū$1`)
    .replaceAll(/U([\u0301\u0303])?\u0304/g, `Ū$1`)
}